"""Rep performance model — per-rep sales analytics snapshots for the AI coach.

A ``RepPerformance`` row is a periodic (weekly/monthly) snapshot of a single
rep's activity and effectiveness, plus the AI coach's qualitative read of it:

* ``metrics``                  — raw + derived numbers (emails_sent, reply_rate,
                                 calls_completed, connect_rate, deals_won, …).
* ``ai_insights``              — Claude's strengths/weaknesses analysis.
* ``coaching_recommendations`` — ranked, specific actions the rep should take.

Snapshots are generated by ``services/sales_coach.py`` (on demand from the
``coaching`` router, or weekly via the ``generate_weekly_coaching`` Celery task).
"""

import uuid
from datetime import datetime

from sqlalchemy import ForeignKey, String, UniqueConstraint, func
from sqlalchemy.dialects.postgresql import JSONB, TIMESTAMP, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base


class RepPerformance(Base):
    __tablename__ = "rep_performance"
    __table_args__ = (
        # One snapshot per rep per period start — regenerating updates in place.
        UniqueConstraint("user_id", "period_type", "period_start", name="uq_rep_performance_period"),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )
    period_type: Mapped[str] = mapped_column(String(20), nullable=False, default="weekly")  # weekly|monthly
    period_start: Mapped[datetime] = mapped_column(TIMESTAMP(timezone=True), nullable=False, index=True)
    period_end: Mapped[datetime] = mapped_column(TIMESTAMP(timezone=True), nullable=False)
    metrics: Mapped[dict] = mapped_column(JSONB, nullable=False, default=dict)
    ai_insights: Mapped[dict] = mapped_column(JSONB, nullable=False, default=dict)
    coaching_recommendations: Mapped[dict] = mapped_column(JSONB, nullable=False, default=dict)
    model_used: Mapped[str | None] = mapped_column(String(50), nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        TIMESTAMP(timezone=True), nullable=False, server_default=func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        TIMESTAMP(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now()
    )

    user = relationship("User")

    def __repr__(self) -> str:
        return f"<RepPerformance user={self.user_id} {self.period_type} {self.period_start:%Y-%m-%d}>"
