"""An index the database has and the model doesn't is a pending `DROP INDEX`.

``alembic revision --autogenerate`` — the workflow CLAUDE.md documents for every
schema change — diffs the live database against ``Base.metadata`` and writes the
statements that make them agree. It is not selective about direction. An index
created by a migration and never declared on its model is, to that diff, an
object the schema no longer wants, so the next autogenerated revision carries an
``op.drop_index`` for it, mixed in with whatever the author actually intended.

Eight were in that state, six of them from ``001_initial_schema``:

* ``ix_contacts_company`` and ``ix_events_enrollment`` are foreign keys, and
  Postgres does **not** index a foreign key for you. They carry the enrolment
  path's per-contact and per-enrollment reads — the hottest joins in the system.
* ``ix_enrollment_status`` is what the queue sweep filters on every five minutes.
* ``ix_companies_naics``, ``ix_consent_contact``, ``ix_lead_scores_company`` and
  the two ``suggestion_outcomes`` ones round it out.

Nothing would have failed at the moment of the drop. The tables would simply get
slower, at whatever data volume made the sequential scan hurt, in a migration
whose message described something else entirely.

The second cost is quieter: tests build their schema from ``Base.metadata``, so
an index absent from the models is absent from every test database. Any future
check that asks "does this query use an index?" would be asking it against a
schema that never had one.

This walks the migrations rather than a hand-kept list, so an index added to a
migration and forgotten in the model fails here on the way in.
"""

import pathlib
import re

import pytest

import app.models  # noqa: F401 — registers every model on Base.metadata
from app.database import Base

VERSIONS = pathlib.Path(__file__).resolve().parents[1] / "alembic" / "versions"

# ``op.create_index("name", "table", [...])`` / ``op.drop_index("name", ...)``.
# Only the leading string literals are needed: the name, and the table for the
# error message.
_CREATE_RE = re.compile(
    r"""create_index\(\s*['"]([^'"]+)['"]\s*,\s*['"]([^'"]+)['"]""", re.S
)
_DROP_RE = re.compile(r"""drop_index\(\s*['"]([^'"]+)['"]""", re.S)


def _migration_indexes() -> tuple[dict[str, tuple[str, str]], set[str]]:
    """``({index_name: (table, migration_file)}, {dropped_index_names})``."""
    created: dict[str, tuple[str, str]] = {}
    dropped: set[str] = set()
    for path in sorted(VERSIONS.glob("*.py")):
        source = path.read_text()
        for match in _CREATE_RE.finditer(source):
            created[match.group(1)] = (match.group(2), path.name)
        for match in _DROP_RE.finditer(source):
            dropped.add(match.group(1))
    return created, dropped


def _metadata_index_names() -> set[str]:
    """Every index name ``Base.metadata`` knows about.

    Covers both spellings: an explicit ``Index(...)`` in ``__table_args__`` and
    a column's ``index=True`` (which SQLAlchemy materialises as an ``Index``
    object on the table, so one traversal finds both).
    """
    return {index.name for table in Base.metadata.tables.values() for index in table.indexes}


def test_the_scan_finds_the_migrations():
    """A regex that matches nothing passes forever and reads as coverage."""
    created, dropped = _migration_indexes()
    assert VERSIONS.is_dir()
    assert len(created) > 100, f"only {len(created)} create_index calls found — scan is broken"
    assert dropped, "no drop_index calls found — the downgrade scan is broken"


def test_the_metadata_scan_finds_indexes():
    names = _metadata_index_names()
    assert len(names) > 100, f"only {len(names)} indexes in Base.metadata — scan is broken"


def test_every_migration_index_is_declared_on_its_model():
    """The check itself.

    A dropped index is exempt: a migration that creates one and a later one that
    removes it leaves nothing in the database to diff against.
    """
    created, dropped = _migration_indexes()
    declared = _metadata_index_names()

    undeclared = {
        name: where
        for name, where in created.items()
        if name not in declared and name not in dropped
    }
    assert not undeclared, (
        "These indexes exist in the database but not in Base.metadata, so the "
        "next `alembic revision --autogenerate` will emit a DROP for each:\n"
        + "\n".join(
            f"  {name} on {table} (created by {migration})"
            for name, (table, migration) in sorted(undeclared.items())
        )
    )


@pytest.mark.parametrize(
    "index_name,table_name",
    [
        # The FK indexes, named individually so a future edit that deletes one
        # fails on the specific thing rather than on a set difference.
        ("ix_contacts_company", "contacts"),
        ("ix_events_enrollment", "outreach_events"),
        ("ix_lead_scores_company", "lead_scores"),
        ("ix_consent_contact", "consent_records"),
        # The queue sweep's filter.
        ("ix_enrollment_status", "outreach_enrollments"),
    ],
)
def test_the_hot_path_indexes_are_present(index_name: str, table_name: str):
    table = Base.metadata.tables[table_name]
    assert index_name in {i.name for i in table.indexes}, (
        f"{index_name} is missing from the {table_name} model"
    )


def test_the_check_would_catch_a_new_undeclared_index(tmp_path, monkeypatch):
    """Self-test: plant the violation and assert the scan names it.

    Without this the test above is indistinguishable from one whose regex has
    quietly stopped matching.
    """
    fake = tmp_path / "versions"
    fake.mkdir()
    (fake / "999_planted.py").write_text(
        'def upgrade():\n'
        '    op.create_index("ix_planted_nobody_declared", "contacts", ["email"])\n'
    )
    monkeypatch.setitem(globals(), "VERSIONS", fake)

    created, dropped = _migration_indexes()
    assert "ix_planted_nobody_declared" in created
    assert "ix_planted_nobody_declared" not in _metadata_index_names()
    assert "ix_planted_nobody_declared" not in dropped


def test_a_created_then_dropped_index_is_not_flagged(tmp_path, monkeypatch):
    """The exemption, self-tested for the same reason."""
    fake = tmp_path / "versions"
    fake.mkdir()
    (fake / "998_transient.py").write_text(
        'def upgrade():\n'
        '    op.create_index("ix_transient", "contacts", ["email"])\n'
    )
    (fake / "999_removes_it.py").write_text(
        'def upgrade():\n    op.drop_index("ix_transient", table_name="contacts")\n'
    )
    monkeypatch.setitem(globals(), "VERSIONS", fake)

    created, dropped = _migration_indexes()
    assert "ix_transient" in created
    assert "ix_transient" in dropped
