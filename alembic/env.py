import asyncio
from logging.config import fileConfig

from alembic import context
from sqlalchemy import pool, text
from sqlalchemy.ext.asyncio import async_engine_from_config

from app.config import get_settings
from app.database import Base

# Import all models so Alembic sees them.
#
# This was a hand-written list of 19 module names, last extended somewhere
# around migration 030, against a package that now holds ~70 modules. Whatever
# it did not name was absent from ``target_metadata``, and autogenerate compares
# the database to *that*: unlisted tables read as "exists in the database, not
# in the models", so a diff would have proposed dropping most of the schema and
# would never propose a change *to* one of them.
#
# That is not hypothetical. ``company_groups`` was one of the unlisted tables,
# which is why migration 078 — the autogenerated one that put ``org_id`` on 71
# tables — silently skipped it and left it as a namespace shared by every tenant
# (fixed in 111). Importing the package is the version of this line that cannot
# fall behind; ``app.models.__init__`` registers every mapped class, and
# ``tests/test_org_scoping_coverage.py`` fails if it stops doing so.
import app.models  # noqa: F401

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

settings = get_settings()
config.set_main_option("sqlalchemy.url", settings.database_url)

target_metadata = Base.metadata


def run_migrations_offline() -> None:
    url = config.get_main_option("sqlalchemy.url")
    context.configure(
        url=url,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


# Alembic creates ``alembic_version.version_num`` as VARCHAR(32) and offers no
# option to widen it. Several revision ids in this project are longer than that
# — ``037_add_user_id_to_email_accounts`` is 33 characters — so a database built
# from nothing dies at 037 with "value too long for type character varying(32)",
# *after* writing 36 revisions worth of schema. Existing databases were created
# before the ids grew and have a wide enough column already, which is why this
# only ever bit a fresh environment: the disaster-recovery case.
#
# The table is created lazily by Alembic on first use, so widening it here — an
# idempotent ALTER, before any revision runs — fixes the fresh build without
# touching a deployed one. Renaming 70+ revision ids would be the alternative,
# and renaming an id that is already stamped in production is not an option.
_VERSION_NUM_WIDTH = 128


def _ensure_version_table_width(connection) -> None:
    dialect = connection.dialect.name
    if dialect != "postgresql":
        return
    connection.execute(text(
        "CREATE TABLE IF NOT EXISTS alembic_version ("
        f" version_num VARCHAR({_VERSION_NUM_WIDTH}) NOT NULL,"
        " CONSTRAINT alembic_version_pkc PRIMARY KEY (version_num))"
    ))
    connection.execute(text(
        "ALTER TABLE alembic_version ALTER COLUMN version_num "
        f"TYPE VARCHAR({_VERSION_NUM_WIDTH})"
    ))


def do_run_migrations(connection):
    # The widening above autobegins a transaction (SQLAlchemy 2.0 commit-as-you-go),
    # and `MigrationContext.configure` snapshots `connection.in_transaction()` into
    # `_in_external_transaction`. Left uncommitted, Alembic concludes the caller owns
    # the transaction, `begin_transaction()` degrades to a nullcontext, and nothing
    # ever commits: `connect()` rolls the whole upgrade back on close. `upgrade head`
    # then exits 0, logs every revision, and writes nothing — which is how a deploy
    # reports success against an unmigrated database.
    #
    # Commit here, *before* configure, so Alembic sees a clean connection and owns
    # the migration transaction itself.
    _ensure_version_table_width(connection)
    connection.commit()
    context.configure(connection=connection, target_metadata=target_metadata)
    with context.begin_transaction():
        context.run_migrations()


async def run_async_migrations() -> None:
    connectable = async_engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    async with connectable.connect() as connection:
        await connection.run_sync(do_run_migrations)
    await connectable.dispose()


def run_migrations_online() -> None:
    asyncio.run(run_async_migrations())


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
